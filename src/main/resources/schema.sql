CREATE TABLE IF NOT EXISTS tech (
    id                 VARCHAR(255)  NOT NULL PRIMARY KEY,
    title              VARCHAR(512)  NOT NULL,
    summary            VARCHAR(2048) NOT NULL,
    topic              VARCHAR(64)   NOT NULL,
    published_at       VARCHAR(64)   NOT NULL,
    source             VARCHAR(128)  NOT NULL
);

-- "user" is a reserved word in both H2 and PostgreSQL, hence app_user.
CREATE TABLE IF NOT EXISTS app_user (
    id                 INT           GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username           VARCHAR(64)   NOT NULL UNIQUE,
    password_hash      VARCHAR(255)  NOT NULL,
    enabled            BOOLEAN       NOT NULL
);

CREATE TABLE IF NOT EXISTS app_user_role (
    user_id            INT           NOT NULL,
    role               VARCHAR(32)   NOT NULL,
    PRIMARY KEY (user_id, role),
    FOREIGN KEY (user_id) REFERENCES app_user (id) ON DELETE CASCADE
);

-- System Design Catalog: one aggregate (system_design) with ordered child rows.
CREATE TABLE IF NOT EXISTS system_design (
    id                 INT           GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name               VARCHAR(255)  NOT NULL UNIQUE,
    classic_example    VARCHAR(512)  NOT NULL,
    core_blueprint     VARCHAR(500)  NOT NULL
);

CREATE TABLE IF NOT EXISTS system_design_keycomponent (
    id                 INT           NOT NULL,
    position           INT           NOT NULL,
    name               VARCHAR(255)  NOT NULL,
    role               VARCHAR(1024) NOT NULL,
    PRIMARY KEY (id, position),
    FOREIGN KEY (id) REFERENCES system_design (id) ON DELETE CASCADE
);

CREATE TABLE IF NOT EXISTS system_design_technology (
    id                 INT           NOT NULL,
    component_position INT           NOT NULL,
    position           INT           NOT NULL,
    technology         VARCHAR(255)  NOT NULL,
    PRIMARY KEY (id, component_position, position),
    FOREIGN KEY (id, component_position)
        REFERENCES system_design_keycomponent (id, position) ON DELETE CASCADE
);

CREATE TABLE IF NOT EXISTS system_design_reuse (
    id                 INT           NOT NULL,
    position           INT           NOT NULL,
    target             VARCHAR(255)  NOT NULL,
    PRIMARY KEY (id, position),
    FOREIGN KEY (id) REFERENCES system_design (id) ON DELETE CASCADE
);
